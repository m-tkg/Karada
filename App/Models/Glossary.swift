    // ------------------------------------------------------------ 体組成

    private static let body = Topic(
        key: "body",
        title: "体組成",
        intro: "体の重さと構成に関わる指標です。",
        entries: [
            Entry(term: "体重", unit: "kg",
                  detail: """
                  記録された体重。前月比 ±0.5kg 以内なら安定、±1.5kg 以上動いた\
