import Foundation

/// 設定 → 「指標の説明」で表示する解説コンテンツ。
///
/// ダッシュボードが見せている値の意味・単位・良い方向・算出方法を、
/// `LocalAnalytics` の実装挙動(二重計上回避・重複除外・前月比の窓・
/// エネルギー収支の式など)と齟齬が出ないよう静的テキストで持つ。
/// JSON デコードには依存しない純粋な値型。
enum Glossary {
    struct Entry: Identifiable {
        let term: String    // 指標名(例「安静時心拍(RHR)」)
        let unit: String?   // 単位(例「bpm」)。無ければ nil
        let detail: String  // 意味・良い方向・注意点
        var id: String { term }
    }

    struct Topic: Identifiable {
        let key: String     // ダッシュボードのカテゴリ key と対応(cardio 等)
        let title: String
        let intro: String?  // トピック冒頭の概要
        let entries: [Entry]
        var id: String { key }
    }

    static let topics: [Topic] = [
        numbers, cardio, activity, sleep, body, walking, diet, cycle, workouts, terms,
    ]

    // ------------------------------------------------------------ いまの数字

    private static let numbers = Topic(
        key: "numbers",
        title: "いまの数字",
        intro: """
        ダッシュボード上部の6つのカードです。いずれも「直近30日の平均」を表示し、\
        「前月比」はその前の30日(31〜60日前)の平均との差を表します。\
        色は、良い方向への変化を緑、悪い方向を赤、どちらとも言えないものを灰で示します。
        """,
        entries: [
            Entry(term: "歩数", unit: "歩/日",
                  detail: """
                  1日に歩いた歩数の平均。iPhone と Apple Watch の両方に記録がある日は、\
                  合計が最も多い1つのソースだけを採用して二重計上を防いでいます。\
                  多いほど良い指標です。
                  """),
            Entry(term: "睡眠", unit: "時間/日",
                  detail: """
                  1晩あたりの実睡眠時間の平均。複数デバイスの記録が重なる時間帯は\
                  マージして重複を除外します(実際に眠っていた正味の長さ)。\
                  一般に長いほど良い指標として扱います。
                  """),
            Entry(term: "安静時心拍", unit: "bpm",
                  detail: """
                  安静にしているときの1分あたりの心拍数(RHR)。低いほど心肺が\
                  効率よく働いているサインで、下がると良い指標です。
                  """),
            Entry(term: "HRV", unit: "ms",
                  detail: """
                  心拍のゆらぎ(心拍変動、SDNN)。自律神経の回復力の目安で、\
                  高いほど回復できている状態。上がると良い指標です。
                  """),
            Entry(term: "体重", unit: "kg",
                  detail: """
                  記録された体重の平均。増減どちらが良いかは目的次第のため、\
                  前月比の色は付けず中立で表示します。
                  """),
            Entry(term: "消費エネルギー", unit: "kcal/日",
                  detail: """
                  身体活動で消費したアクティブエネルギーの平均(基礎代謝は含みません)。\
                  歩数と同様、デバイス間の二重計上を避けて集計します。\
                  活動量の目安として、多いほど良い指標です。
                  """),
        ])

    // ------------------------------------------------------------ 心肺コンディション

    private static let cardio = Topic(
        key: "cardio",
        title: "心肺コンディション",
        intro: "心臓と肺の状態、回復力に関わる指標です。",
        entries: [
            Entry(term: "安静時心拍", unit: "bpm",
                  detail: """
                  安静時の1分あたりの心拍数。低く安定しているほど心肺機能が\
                  良好なサイン。逆に前月より上がっているときは、疲労・睡眠不足・\
                  体調変化のサインのことがあります。
                  """),
            Entry(term: "HRV / SDNN", unit: "ms",
                  detail: """
                  心拍の間隔のばらつき(SDNN)。自律神経のバランスと回復力の指標で、\
                  高いほど回復できている状態です。ストレスや睡眠不足が続くと\
                  下がりやすくなります。
                  """),
            Entry(term: "VO2 max", unit: "mL/kg/min",
                  detail: """
                  最大酸素摂取量。持久系の体力(有酸素フィットネス)の目安で、\
                  高いほど心肺の持久力が高いことを示します。有酸素運動を続けると\
                  ゆっくり上がっていきます。
                  """),
        ])

    // ------------------------------------------------------------ 活動量

